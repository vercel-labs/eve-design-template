import {
  copyFile,
  lstat,
  mkdir,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import {
  displayPath,
  knowledgeRoot,
  repoRoot,
  verifyKnowledge,
} from './knowledge.mjs';

const outputRoot = resolve(repoRoot, 'agent/sandbox/workspace/knowledge');
const generatedRoot = resolve(repoRoot, 'generated');

async function collectFiles(directory) {
  const files = [];
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((left, right) => left.name.localeCompare(right.name));

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(`Knowledge cannot contain symlinks: ${displayPath(path)}`);
    }
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(path)));
    } else if (entry.isFile()) {
      files.push(path);
    }
  }

  return files;
}

const manifest = await verifyKnowledge();
const files = await collectFiles(knowledgeRoot);

await rm(outputRoot, { force: true, recursive: true });
await mkdir(outputRoot, { recursive: true });

let preparedFileCount = 0;
for (const source of files) {
  const destinationPath = relative(knowledgeRoot, source);
  if (
    destinationPath === 'manifest.json' ||
    destinationPath === 'manifest.schema.json'
  ) {
    continue;
  }
  const destination = resolve(outputRoot, destinationPath);
  const stats = await lstat(source);
  if (!stats.isFile()) continue;

  await mkdir(dirname(destination), { recursive: true });
  await copyFile(source, destination);
  preparedFileCount += 1;
}

await writeFile(
  resolve(outputRoot, 'manifest.json'),
  `${JSON.stringify(
    {
      schemaVersion: manifest.schemaVersion,
      status: manifest.status,
      sources: manifest.sources,
    },
    null,
    2,
  )}\n`,
);
preparedFileCount += 1;

await mkdir(generatedRoot, { recursive: true });
await writeFile(
  resolve(generatedRoot, 'config.ts'),
  `// Generated by scripts/prepare-knowledge.mjs. Do not edit.
interface DesignAgentConfig {
  readonly status: 'draft' | 'approved';
  readonly designOwnerSlackId: string | null;
  readonly allowGeneralGuidance: boolean;
  readonly allowedChannelIds: readonly string[];
  readonly allowedUserIds: readonly string[];
}

export const designAgentConfig: DesignAgentConfig = ${JSON.stringify(
    {
      status: manifest.status,
      designOwnerSlackId: manifest.agent.designOwnerSlackId,
      allowGeneralGuidance: manifest.agent.allowGeneralGuidance,
      allowedChannelIds: manifest.agent.allowedChannelIds,
      allowedUserIds: manifest.agent.allowedUserIds,
    },
    null,
    2,
  )};\n`,
);

console.log(`Prepared ${preparedFileCount} knowledge files.`);
